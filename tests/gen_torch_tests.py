"""Generates tests/torch/BUILD from the upstream PyTorch test sources.

The coverage policy is collect-everything-then-exclude: every upstream
module that instantiates device-generic tests for a PrivateUse1 backend gets
a `torch_tpu_oss_torch_test` target, customized (or deliberately omitted,
with a reason) by tests/torch_test_targets.py. Target names map to the file:
test_nn.py -> "test_nn", nn/test_pooling.py -> "nn_test_pooling".

Discovery does not parse source text: each `test_*.py` under
--pytorch_test_dir is imported in a fresh subprocess with a fake python-only
`tpu` PrivateUse1 backend registered and PYTORCH_TESTING_DEVICE_ONLY_FOR=tpu,
and the probe counts the `DeviceTypeTestBase` subclasses the import actually
materialized. A module is eligible iff that count is nonzero — the framework
applies its own only_for/except_for rules — so re-generating against a new
PyTorch checkout automatically picks up added, removed, or renamed modules.
No TPU hardware is needed.

Run as a pre-step of the suite (also how CI uses it):

  bazel run //tests:gen_torch_tests -- --pytorch_test_dir=/path/to/pytorch/test
  bazel test //tests/torch:all

The generated BUILD is not checked in (see .gitignore): it is a function of
the PyTorch checkout under test and is regenerated per run.
"""

import concurrent.futures
import os
import pathlib
import subprocess
import sys

from absl import app
from absl import flags

from tests import torch_test_targets

_PYTORCH_TEST_DIR = flags.DEFINE_string(
    "pytorch_test_dir",
    os.environ.get("TORCH_TPU_INTERNAL_PYTORCH_TEST_DIR"),
    "The test/ directory of a pytorch/pytorch checkout.",
)
_OUTPUT = flags.DEFINE_string(
    "output",
    None,
    "Path of the BUILD file to write. Defaults to tests/torch/BUILD under"
    " BUILD_WORKSPACE_DIRECTORY (set by `bazel run`).",
)

_PROBE_TIMEOUT_SECONDS = 240

# Runs in a fresh interpreter per module: registers a fake `tpu` PrivateUse1
# backend (no hardware, no torch_tpu import), imports the module, and prints
# how many DeviceTypeTestBase subclasses instantiate_device_type_tests()
# materialized in its namespace.
_PROBE_SOURCE = """
import importlib.util, pathlib, sys, types

test_dir, module_id = sys.argv[1], sys.argv[2]
module_file = pathlib.Path(test_dir, module_id + ".py")
sys.path.insert(0, test_dir)
if "/" in module_id:
    # Mirror `python test/<subdir>/x.py`: the file's directory is on sys.path.
    sys.path.insert(0, str(module_file.parent))

import torch

torch.utils.rename_privateuse1_backend("tpu")
fake = types.ModuleType("torch.tpu")
fake.is_available = lambda: True
fake.device_count = lambda: 1
fake.current_device = lambda: 0
torch._register_device_module("tpu", fake)

from torch.testing._internal.common_device_type import DeviceTypeTestBase

spec = importlib.util.spec_from_file_location(
    module_id.replace("/", "."), module_file
)
module = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = module
spec.loader.exec_module(module)
count = sum(
    1
    for value in vars(module).values()
    if isinstance(value, type) and issubclass(value, DeviceTypeTestBase)
)
print(count)
"""

_BUILD_HEADER = """\
# Generated by `bazel run //tests:gen_torch_tests` -- do not edit.
#
# One torch_tpu_oss_torch_test target per upstream pytorch/test module that
# instantiates device-generic tests for the tpu backend, probed against
# {test_dir} (torch {torch_version}):
# {wired} targets; {omitted} eligible-or-gone modules deliberately omitted
# (reasons in tests/torch_test_targets.py); {errors} modules unprobeable
# (import errors, listed in the generator log).
#
# Run the whole suite with: bazel test //tests/torch:all

load("//build_files:build_defs.bzl", "torch_tpu_oss_torch_test")

package(default_applicable_licenses = ["//:license"])
"""


def _probe_module(test_dir, module_name):
  """Returns the instantiated-class count for a module, or an error string."""
  env = dict(
      os.environ,
      PYTORCH_TESTING_DEVICE_ONLY_FOR="tpu",
      TORCH_DEVICE_BACKEND_AUTOLOAD="0",
  )
  try:
    result = subprocess.run(
        [sys.executable, "-c", _PROBE_SOURCE, test_dir, module_name],
        capture_output=True,
        text=True,
        timeout=_PROBE_TIMEOUT_SECONDS,
        env=env,
        check=False,
    )
  except subprocess.TimeoutExpired:
    return "import timed out"
  if result.returncode != 0:
    stderr = result.stderr.strip().splitlines() or ["(no stderr)"]
    return "import failed: " + stderr[-1][:200]
  # Some upstream files sys.exit(0) at import (e.g. optional deps missing);
  # the probe then produces no count line.
  digits = [
      line for line in result.stdout.strip().splitlines() if line.isdigit()
  ]
  if not digits:
    return "probe produced no count (module exited during import)"
  return int(digits[-1])


def _discover(test_dir):
  """Probes every test_*.py; returns (eligible set, import-error dict)."""
  root = pathlib.Path(test_dir)
  # distributed/ is deferred: multi-process/multi-device orchestration.
  modules = sorted(
      str(p.relative_to(root))[: -len(".py")]
      for p in root.rglob("test_*.py")
      if "distributed" not in p.relative_to(root).parts
  )
  with concurrent.futures.ThreadPoolExecutor(max_workers=16) as pool:
    results = dict(
        zip(modules, pool.map(lambda m: _probe_module(test_dir, m), modules))
    )
  eligible = {m for m, r in results.items() if isinstance(r, int) and r}
  errors = {m: r for m, r in results.items() if isinstance(r, str)}
  return len(modules), eligible, errors


def _render_target(module, kwargs):
  lines = [
      "",
      "torch_tpu_oss_torch_test(",
      f'    name = "{module.replace("/", "_")}",',
  ]
  def quote(value):
    # "$" doubles to survive Bazel's make-variable expansion of env/args.
    escaped = (
        value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "$$")
    )
    return f'"{escaped}"'

  if kwargs.get("args"):
    rendered = ", ".join(quote(a) for a in kwargs["args"])
    lines.append(f"    args = [{rendered}],")
  if kwargs.get("extra_deps"):
    lines.append("    extra_deps = [")
    lines.extend(f'        "{d}",' for d in sorted(kwargs["extra_deps"]))
    lines.append("    ],")
  if kwargs.get("shard_count"):
    lines.append(f"    shard_count = {kwargs['shard_count']},")
  lines.append(f'    torch_test_module = "{module}",')
  lines.append(")")
  return "\n".join(lines)


def _note(message):
  print(f"NOTE: {message}", file=sys.stderr)


def main(argv):
  del argv
  test_dir = _PYTORCH_TEST_DIR.value
  if not test_dir:
    raise app.UsageError(
        "--pytorch_test_dir (or TORCH_TPU_INTERNAL_PYTORCH_TEST_DIR) is"
        " required."
    )
  if not pathlib.Path(test_dir, "test_torch.py").is_file():
    raise app.UsageError(
        f"--pytorch_test_dir={test_dir} does not look like a pytorch/pytorch"
        " test/ directory (no test_torch.py)."
    )
  output = _OUTPUT.value
  if not output:
    workspace = os.environ.get("BUILD_WORKSPACE_DIRECTORY")
    if not workspace:
      raise app.UsageError(
          "--output is required outside `bazel run` (BUILD_WORKSPACE_DIRECTORY"
          " is not set)."
      )
    output = os.path.join(workspace, "tests", "torch", "BUILD")

  # The generated targets need a torch that ships
  # PrivateUse1TestBase.set_test_configs (2.13+) — and probing v2.13+ sources
  # against an older torch's testing framework misreports import errors — so
  # require it up front rather than generating a misleading inventory.
  import torch  # pylint: disable=g-import-not-at-top
  from torch.testing._internal import common_device_type  # pylint: disable=g-import-not-at-top

  if not hasattr(common_device_type.PrivateUse1TestBase, "set_test_configs"):
    sys.exit(
        f"torch {torch.__version__} predates"
        " PrivateUse1TestBase.set_test_configs (torch 2.13). Select a newer"
        " torch, e.g. bazel run --//:_torch_version=2.13.0"
        " //tests:gen_torch_tests."
    )

  total, eligible, errors = _discover(test_dir)
  kwargs_map = dict(torch_test_targets.TARGET_KWARGS)
  omitted = torch_test_targets.OMITTED_TEST_MODULES

  # A probe import can fail for environment reasons a real target does not
  # have (e.g. an import path that needs the real backend), so an import
  # error is indeterminate rather than disqualifying: a TARGET_KWARGS entry
  # (even {}) is a human assertion that the module is eligible and keeps it
  # wired; an OMITTED entry keeps it out.
  force_wired = set(errors) & set(kwargs_map)

  problems = []
  # An unprobeable module that could plausibly be eligible (its source
  # mentions instantiate_device_type_tests at all) must be classified by a
  # human: give it TARGET_KWARGS (even {}) or omit it with a reason.
  unclassified_errors = {
      m: e
      for m, e in errors.items()
      if m not in kwargs_map
      and m not in omitted
      and "instantiate_device_type_tests"
      in pathlib.Path(test_dir, f"{m}.py").read_text(errors="replace")
  }
  if unclassified_errors:
    problems.append(
        "unprobeable modules mention instantiate_device_type_tests but are"
        " not classified in tests/torch_test_targets.py:"
        f" {unclassified_errors}"
    )
  contradictions = sorted(set(kwargs_map) & set(omitted))
  if contradictions:
    problems.append(
        f"modules both in TARGET_KWARGS and OMITTED_TEST_MODULES:"
        f" {contradictions}"
    )
  if problems:
    sys.exit("gen_torch_tests: " + "; ".join(problems))

  for module, error in sorted(errors.items()):
    suffix = "; wired by its TARGET_KWARGS entry" if module in force_wired else ""
    _note(f"probe import error ({module}): {error}{suffix}")
  for module in sorted(set(omitted) & eligible):
    _note(f"eligible module deliberately omitted ({module}): {omitted[module]}")
  for module in sorted(set(kwargs_map) - eligible - force_wired):
    _note(
        f"stale TARGET_KWARGS entry ({module}): module is not eligible for"
        " this checkout/torch pairing; entry ignored"
    )

  wired = sorted((eligible | force_wired) - set(omitted))
  header = _BUILD_HEADER.format(
      test_dir=test_dir,
      torch_version=torch.__version__,
      wired=len(wired),
      omitted=len(omitted),
      errors=len(errors),
  )
  body = "".join(
      _render_target(module, kwargs_map.get(module, {})) + "\n"
      for module in wired
  )
  out_path = pathlib.Path(output)
  out_path.parent.mkdir(parents=True, exist_ok=True)
  out_path.write_text(header + body)

  print(
      f"gen_torch_tests: probed {total} test_*.py under {test_dir} (torch"
      f" {torch.__version__}): {len(eligible)} instantiate device-generic"
      f" tests for tpu; wrote {len(wired)} targets to {output}"
      f" ({len(set(omitted) & eligible)} eligible modules omitted,"
      f" {len(errors)} unprobeable).",
      file=sys.stderr,
  )


if __name__ == "__main__":
  app.run(main)
