"""Tests for the device module with TPU backend."""

import tempfile
import warnings
from absl.testing import absltest
from absl.testing import parameterized
import torch
from torch._dynamo.device_interface import DeviceInterface
from torch._dynamo.device_interface import get_interface_for_device
from torch_tpu._internal.device import _device_module
from torch_tpu._internal.utils import annotations
from tests.device import device_module_testing


def setUpModule():
  # Test the internal torch.tpu device APIs that PyTorch uses, e.g. through the
  # TorchDynamo device interface.
  annotations._internal_apis_allowed_for_testing = True  # pylint: disable=protected-access


# Test cases are defined in device_module_testing.DeviceModuleBase
class TpuDeviceModuleTest(
    device_module_testing.DeviceModuleBase,
    absltest.TestCase,  # ABSLTEST_OK=Reference to absltest.TestCase
):

  @property
  def device_module(self):
    return torch.tpu

  # ------------------------------------------------------------------
  # PrivateUse1 backend attrs generated by
  # torch.utils.generate_methods_for_privateuse1_backend() in _loader.py.
  # These attrs are absent unless _loader.py calls generate_methods_*; they
  # are what lets user code use idioms like `if t.is_tpu` and `model.tpu()`.
  # ------------------------------------------------------------------

  def test_tensor_is_tpu_attr(self):
    t = torch.zeros(1, device="tpu")
    self.assertTrue(hasattr(t, "is_tpu"))
    self.assertTrue(t.is_tpu)
    self.assertFalse(torch.zeros(1).is_tpu)

  def test_tensor_tpu_method(self):
    t = torch.zeros(1).tpu()
    self.assertEqual(t.device.type, "tpu")

  def test_module_tpu_method(self):
    m = torch.nn.Linear(1, 1).tpu()
    self.assertEqual(next(m.parameters()).device.type, "tpu")

  def test_device_interface_registration_always_wins(self):
    """Verifies device_interface from _loader.py is registered as device interface."""
    iface = get_interface_for_device("tpu")
    self.assertEqual(iface, _device_module.TpuDeviceInterface)
    self.assertTrue(issubclass(iface, _device_module.TpuDeviceModule))
    self.assertTrue(issubclass(iface, DeviceInterface))

  def test_torch_tpu_exports_match_device_class_surface(self):
    """Verifies torch.tpu.__all__ stays in sync with TpuDeviceModule."""
    expected_exports = (
        {
            name
            for name in dir(_device_module.TpuDeviceModule)
            if not name.startswith("_")
        }
        | {
            name
            for name in _device_module._DeviceModuleMeta.__dict__
            if not name.startswith("_")
        }
        | {
            name
            for name in _device_module.__tt_api_stages__
            if not name.startswith("_")
        }
    )
    actual_exports = set(torch.tpu.__all__) - {
        "compiler",
        "distributed",
        "ops",
        "optimizers",
        "pallas",
        "profiler",
    }
    self.assertEqual(actual_exports, expected_exports)

  @parameterized.parameters(
      "_is_in_bad_fork",
      "_get_generator",
      "_get_local_device_attributes",
  )
  def test_private_hooks_accessible(self, hook: str):
    """Verifies private hooks remain reachable on torch.tpu."""
    self.assertTrue(callable(getattr(torch.tpu, hook)))

  def test_hidden_attributes_not_in_dir(self):
    """Verifies private attributes do not appear in dir(torch.tpu)."""
    self.assertEmpty([name for name in dir(torch.tpu) if name.startswith("_")])

  def test_dynamo_traces_torch_tpu_without_recompilation(self):
    """Verifies Dynamo traces torch.tpu calls without graph breaks or recompiles."""
    # Warm up @experimental once-per-process warnings outside Dynamo so the
    # test does not depend on whether another test ran first and triggered
    # `sys._getframe` in `annotations._create_warning_wrapper`.
    _ = (
        torch.tpu.device_count(),
        torch.tpu.is_available(),
    )
    compile_count = 0

    def counting_backend(gm, example_inputs):
      del example_inputs
      nonlocal compile_count
      compile_count += 1
      return gm.forward

    @torch.compile(fullgraph=True, backend=counting_backend)
    def fn(x):
      dev_mod = torch.get_device_module("tpu")
      if (
          torch.accelerator.current_accelerator().type == "tpu"
          and torch.tpu.device_count() > 0
          and dev_mod.is_available()
          and torch.accelerator.current_device_index() >= 0
      ):
        return x + 1
      return x

    x = torch.ones(2)
    self.assertTrue(torch.equal(fn(x), x + 1))
    self.assertTrue(torch.equal(fn(x), x + 1))
    self.assertEqual(compile_count, 1)

  def test_device_interface_maybe_exchange_device(self):
    """Verifies TpuDeviceInterface implements maybe_exchange_device for Dynamo."""
    iface = get_interface_for_device("tpu")
    self.assertTrue(hasattr(iface, "maybe_exchange_device"))
    self.assertFalse(hasattr(self.device_module, "maybe_exchange_device"))
    self.assertEqual(iface.maybe_exchange_device(0), 0)
    self.assertEqual(iface.maybe_exchange_device(-1), -1)

  def test_device_interface_exchange_device(self):
    """Verifies TpuDeviceInterface implements exchange_device for Dynamo."""
    iface = get_interface_for_device("tpu")
    self.assertTrue(hasattr(iface, "exchange_device"))
    self.assertFalse(hasattr(self.device_module, "exchange_device"))
    self.assertEqual(iface.exchange_device(0), 0)
    self.assertEqual(iface.exchange_device(-1), -1)

  def test_dynamic_attribute_memoization(self):
    """Verifies attributes resolved via __getattr__ are memoized on subsequent accesses."""
    p1 = self.device_module.Precision
    p2 = self.device_module.Precision
    self.assertIs(p1, p2)

  def test_get_device_properties_multi_processor_count(self):
    # The deprecated `multi_processor_count` stays readable through
    # `torch.tpu` and the Dynamo device interface.
    props = self.device_module.get_device_properties()
    iface_props = get_interface_for_device("tpu").get_device_properties("tpu")
    with self.assertWarns(DeprecationWarning):
      self.assertEqual(props.multi_processor_count, 1)
      self.assertEqual(iface_props.multi_processor_count, 1)

  def test_get_multi_processor_count(self):
    """Verifies TpuDeviceInterface implements get_multi_processor_count and not exposed on torch.tpu."""
    iface = get_interface_for_device("tpu")
    self.assertFalse(hasattr(self.device_module, "get_multi_processor_count"))
    self.assertEqual(iface.get_multi_processor_count(), 1)
    self.assertEqual(iface.get_multi_processor_count("tpu"), 1)

  def test_get_compute_capability(self):
    """Verifies TpuDeviceInterface implements get_compute_capability and not exposed on torch.tpu."""
    iface = get_interface_for_device("tpu")
    self.assertFalse(hasattr(self.device_module, "get_compute_capability"))
    self.assertIsInstance(iface.get_compute_capability(), str)
    self.assertIsInstance(iface.get_compute_capability("tpu"), str)
    self.assertEqual(iface.get_compute_capability(), "")
    self.assertEqual(iface.get_compute_capability("tpu"), "")

  def test_is_triton_capable(self):
    """Verifies TpuDeviceInterface implements is_triton_capable and not exposed on torch.tpu."""
    iface = get_interface_for_device("tpu")
    self.assertFalse(hasattr(self.device_module, "is_triton_capable"))
    self.assertFalse(iface.is_triton_capable())
    self.assertFalse(iface.is_triton_capable(device=None))

  def test_is_gpu(self):
    """Verifies TpuDeviceInterface implements is_gpu and not exposed on torch.tpu."""
    iface = get_interface_for_device("tpu")
    self.assertTrue(hasattr(iface, "is_gpu"))
    self.assertFalse(hasattr(self.device_module, "is_gpu"))
    self.assertFalse(iface.is_gpu())
    self.assertFalse(self.device_module._is_gpu())

  def test_window_num_stripes(self):
    """Tests torch.tpu.distributed.window_num_stripes property."""
    original = torch.tpu.distributed.window_num_stripes
    try:
      self.assertEqual(original, 4)
      torch.tpu.distributed.window_num_stripes = 8
      self.assertEqual(torch.tpu.distributed.window_num_stripes, 8)
    finally:
      torch.tpu.distributed.window_num_stripes = original

  def test_window_stripe_chunk_mb(self):
    """Tests torch.tpu.distributed.window_stripe_chunk_mb property."""
    original = torch.tpu.distributed.window_stripe_chunk_mb
    try:
      self.assertEqual(original, 8)
      torch.tpu.distributed.window_stripe_chunk_mb = 16
      self.assertEqual(torch.tpu.distributed.window_stripe_chunk_mb, 16)
    finally:
      torch.tpu.distributed.window_stripe_chunk_mb = original

  def test_compute_window_stripe_count(self):
    """Tests stripe count calculation logic across tensor byte sizes and configurations."""
    from torch_tpu._internal.device import _device_ops_backend

    compute_fn = getattr(
        _device_ops_backend, "_compute_window_stripe_count", None
    )
    if compute_fn is None:
      return

    tpu_dist = torch.tpu.distributed
    original_stripes = tpu_dist.window_num_stripes
    original_chunk_mb = tpu_dist.window_stripe_chunk_mb
    try:
      # Default: 8 MB chunk, 4 max stripes
      tpu_dist.window_num_stripes = 4
      tpu_dist.window_stripe_chunk_mb = 8
      mb = 1024 * 1024

      self.assertEqual(compute_fn(0), 1)
      self.assertEqual(compute_fn(1024), 1)
      self.assertEqual(compute_fn(7 * mb), 1)
      self.assertEqual(compute_fn(8 * mb), 1)
      self.assertEqual(compute_fn(15 * mb), 1)
      self.assertEqual(compute_fn(16 * mb), 2)
      self.assertEqual(compute_fn(23 * mb), 2)
      self.assertEqual(compute_fn(24 * mb), 3)
      self.assertEqual(compute_fn(31 * mb), 3)
      self.assertEqual(compute_fn(32 * mb), 4)
      self.assertEqual(compute_fn(64 * mb), 4)
      self.assertEqual(compute_fn(128 * mb), 4)

      # Custom: 4 MB chunk, 8 max stripes
      tpu_dist.window_num_stripes = 8
      tpu_dist.window_stripe_chunk_mb = 4

      self.assertEqual(compute_fn(4 * mb), 1)
      self.assertEqual(compute_fn(8 * mb), 2)
      self.assertEqual(compute_fn(16 * mb), 4)
      self.assertEqual(compute_fn(32 * mb), 8)
      self.assertEqual(compute_fn(64 * mb), 8)
    finally:
      tpu_dist.window_num_stripes = original_stripes
      tpu_dist.window_stripe_chunk_mb = original_chunk_mb

  def test_torch_save_load_no_warnings(self):
    """Verifies that torch.save and torch.load do not emit warnings on TPU tensors."""
    tensor = torch.zeros(10, device="tpu")
    with warnings.catch_warnings(record=True) as w:
      warnings.simplefilter("always")
      with tempfile.NamedTemporaryFile() as f:
        torch.save(tensor, f)
        f.seek(0)
        _ = torch.load(f)
      self.assertEmpty(
          w, msg=f"Expected no warnings but got {[str(x.message) for x in w]}"
      )


if __name__ == "__main__":
  absltest.main()
