"""Tests for the device module with TPU backend."""

from unittest import mock
from absl.testing import absltest
import torch
from tests.device import device_module_testing
from torch_tpu._internal.utils import hardware


# Test cases are defined in device_module_testing.DeviceModuleBase
class TpuDeviceModuleTest(
    device_module_testing.DeviceModuleBase, absltest.TestCase
):

  @property
  def device_module(self):
    return torch.tpu

  # ------------------------------------------------------------------
  # Single-device-per-process contract (RFC #2213): device_count() == 1 and
  # current_device() == 0, mirroring torch.cuda under CUDA_VISIBLE_DEVICES=n.
  # ------------------------------------------------------------------

  def _materialize(self):
    """Forces lazy runtime init by materializing a tensor on the device."""
    t = torch.ones(1, device=torch.accelerator.current_accelerator())
    _ = t.item()

  def test_device_count_is_one_post_init(self):
    self._materialize()
    self.assertTrue(self.device_module.is_initialized())
    self.assertEqual(self.device_module.device_count(), 1)

  def test_current_device_is_zero_int(self):
    self._materialize()
    cur = self.device_module.current_device()
    self.assertEqual(cur, 0)
    self.assertIsInstance(cur, int)

  def test_device_count_preinit_reports_one_not_host_chip_count(self):
    """Pre-init device_count() is the per-process count (1), not host chips.

    Regression test for RFC #2213: before this fix an uninitialized TPU module
    returned hardware.get_tpu_device_count() (the host-wide PCI chip count,
    e.g. 8 on a multi-chip host), diverging from the contract.
    """
    with mock.patch.object(
        self.device_module, "is_initialized", return_value=False
    ), mock.patch.object(hardware, "get_tpu_device_count", return_value=8):
      self.assertEqual(self.device_module.device_count(), 1)

  def test_device_count_preinit_zero_when_no_tpu(self):
    with mock.patch.object(
        self.device_module, "is_initialized", return_value=False
    ), mock.patch.object(hardware, "get_tpu_device_count", return_value=0):
      self.assertEqual(self.device_module.device_count(), 0)

  def test_accelerator_parity(self):
    self._materialize()
    self.assertEqual(torch.accelerator.current_accelerator().type, "tpu")
    self.assertEqual(torch.accelerator.device_count(), 1)
    self.assertEqual(torch.accelerator.current_device_index(), 0)

  # ------------------------------------------------------------------
  # PrivateUse1 backend attrs generated by
  # torch.utils.generate_methods_for_privateuse1_backend() in _loader.py.
  # These attrs are absent unless _loader.py calls generate_methods_*; they
  # are what lets user code use idioms like `if t.is_tpu` and `model.tpu()`.
  # ------------------------------------------------------------------

  def test_tensor_is_tpu_attr(self):
    t = torch.zeros(1, device="tpu")
    self.assertTrue(hasattr(t, "is_tpu"))
    self.assertTrue(t.is_tpu)
    self.assertFalse(torch.zeros(1).is_tpu)

  def test_tensor_tpu_method(self):
    t = torch.zeros(1).tpu()
    self.assertEqual(t.device.type, "tpu")

  def test_module_tpu_method(self):
    m = torch.nn.Linear(1, 1).tpu()
    self.assertEqual(next(m.parameters()).device.type, "tpu")


if __name__ == "__main__":
  absltest.main()
