std::string_view ToString(OpName op_name) {
  auto it = std::lower_bound(
      std::begin(kOpNames), std::end(kOpNames), op_name,
      [](const OpNameEntry& entry, OpName val) { return entry.op_name < val; });
  if (it != std::end(kOpNames) && it->op_name == op_name) {
    return it->name;
  }
  std::cerr << "ToString failed for op value: " << static_cast<int>(op_name)
            << std::endl
            << std::flush;
  return "unknown_op";
}

std::string_view ToBaseName(const OpName op_name) {
  if (op_name == OpName::kIndexPutImpl_) {
    return "index_put_";
  }
  if (op_name == OpName::kCtcLossTensor) {
    return "_ctc_loss";
  }

  auto full_name = ToString(op_name);
  if (!full_name.empty() && full_name[0] == '_') {
    full_name.remove_prefix(1);
  }

  // Distributed ops are named like "distributed.foo" and base name is the same
  // as the op name.
  if (absl::StartsWith(full_name, "distributed.")) {
    return full_name;
  }
  const auto last_dot_pos = full_name.rfind('.');
  return last_dot_pos == std::string_view::npos
             ? full_name
             : full_name.substr(0, last_dot_pos);
}

