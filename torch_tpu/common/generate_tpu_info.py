"""Generates C++ TPU hardware info definitions from jax._src.tpu_info."""

from collections.abc import Sequence
import importlib

from absl import app
from absl import flags
from jax.experimental.pallas import tpu as pltpu

_OUTPUT = flags.DEFINE_string(  # NONSTANDARD_FLAG_NAME_OK=utility
    "output",
    None,
    "Path to output generated C++ inc file (tpu_info_data.inc).",
)


def _chip_enum_name(chip: pltpu.ChipVersion) -> str:
  """Converts ChipVersion to C++ enum identifier, e.g. TPU_V4 -> kTPUv4."""
  return "kTPU" + str(chip)


def _format_int64(val: int) -> str:
  return f"{val}LL" if abs(val) > 2147483647 else str(val)


def generate_inc() -> str:
  """Generates the C++ .inc file contents with hardware tables and lookup functions."""

  # ToString
  tostring_cases = []
  for chip in pltpu.ChipVersion:
    c_name = _chip_enum_name(chip)
    tostring_cases.append(
        f'    case ChipVersion::{c_name}: return "{chip.value}";'
    )
  tostring_str = "\n".join(tostring_cases)

  # These are the names returned by pjrt.
  candidates = [
      "TPU v2",
      "TPU v3",
      "TPU v4",
      "TPU v4 lite",
      "TPU v5",
      "TPU v5e",
      "TPU v5 lite",
      "TPU v5p",
      "TPU v6e",
      "TPU v6 lite",
      "TPU7",
      "TPU7x",
      "TPU8i",
      "TPU8t",
  ]
  device_kind_map = {}
  # chip_version_from_device_kind is not exported by pltpu.
  tpu_info = importlib.import_module("jax._src.tpu_info")
  for cand in candidates:
    ver = tpu_info.chip_version_from_device_kind(cand)
    if ver is not None:
      device_kind_map[cand] = _chip_enum_name(ver)

  device_kind_checks = []
  for kind, c_name in device_kind_map.items():
    device_kind_checks.append(
        f'  if (device_kind == "{kind}") return ChipVersion::{c_name};'
    )
  device_kind_checks_str = "\n".join(device_kind_checks)

  # TpuInfo generation per chip
  chip_info_cases = []
  for chip in pltpu.ChipVersion:
    c_name = _chip_enum_name(chip)
    try:
      info = pltpu.get_tpu_info_for_chip(chip, 1)
    except Exception:
      continue

    sc_str = "std::nullopt"
    if info.sparse_core is not None:
      sc = info.sparse_core
      sc_str = (
          f"SparseCoreInfo{{\n            .num_cores = {sc.num_cores},\n       "
          f"     .num_subcores = {sc.num_subcores},\n            .num_lanes ="
          f" {sc.num_lanes},\n            .vmem_capacity_bytes ="
          f" {_format_int64(sc.vmem_capacity_bytes)},\n           "
          " .dma_granule_size_bytes ="
          f" {_format_int64(sc.dma_granule_size_bytes)},\n      }}"
      )

    chip_info_cases.append(f"""    case ChipVersion::{c_name}:
      return TpuInfo{{
          .chip_version = ChipVersion::{c_name},
          .generation = {info.generation},
          .num_cores = {info.num_cores},
          .num_lanes = {info.num_lanes},
          .num_sublanes = {info.num_sublanes},
          .mxu_column_size = {info.mxu_column_size},
          .num_mxus = {info.num_mxus},
          .num_accumulators = {info.num_accumulators},
          .vmem_capacity_bytes = {_format_int64(info.vmem_capacity_bytes)},
          .cmem_capacity_bytes = {_format_int64(info.cmem_capacity_bytes)},
          .smem_capacity_bytes = {_format_int64(info.smem_capacity_bytes)},
          .hbm_capacity_bytes = {_format_int64(info.hbm_capacity_bytes)},
          .mem_bw_bytes_per_second = {_format_int64(info.mem_bw_bytes_per_second)},
          .bf16_ops_per_second = {_format_int64(info.bf16_ops_per_second)},
          .int8_ops_per_second = {_format_int64(info.int8_ops_per_second)},
          .fp8_ops_per_second = {_format_int64(info.fp8_ops_per_second)},
          .int4_ops_per_second = {_format_int64(info.int4_ops_per_second)},
          .sparse_core = {sc_str},
          .is_lite = {"true" if info.is_lite else "false"},
          .is_split_chip = {"true" if info.is_split_chip else "false"},
          .is_megacore = {"true" if info.is_megacore else "false"},
      }};""")

  chip_info_cases_str = "\n".join(chip_info_cases)

  return f"""// AUTO-GENERATED by generate_pltpu.py from third_party/py/jax/_src/pltpu.py.
// DO NOT EDIT DIRECTLY.


std::string_view ToString(ChipVersion chip_version) {{
  switch (chip_version) {{
{tostring_str}
    default:
      return "unknown";
  }}
}}

std::optional<ChipVersion> ChipVersionFromDeviceKind(std::string_view device_kind) {{
{device_kind_checks_str}
  return std::nullopt;
}}

std::optional<TpuInfo> GetTpuInfoForChip(ChipVersion chip_version) {{
  switch (chip_version) {{
{chip_info_cases_str}
    default:
      return std::nullopt;
  }}
}}
"""


def main(argv: Sequence[str]) -> None:
  del argv

  if _OUTPUT.value:
    inc_code = generate_inc()
    with open(_OUTPUT.value, "w") as f:
      f.write(inc_code)


if __name__ == "__main__":
  app.run(main)
