# Activates the CI network policy in policy.env (see ci/README.md). In GitHub
# Actions, every later step runs in a fresh shell, so GITHUB_ENV is the
# hand-off: the policy values and CURL_HOME are appended to it (noxfile.py uses
# the same mechanism for local runs). curl has no environment variables for
# retries and reads only $CURL_HOME/.curlrc, so that file is rendered from the
# DOWNLOAD_* values.

set -euo pipefail

policy_dir="$(cd -- "$(dirname -- "$0")" && pwd -P)"

# uv and pip read UV_HTTP_* and PIP_* from the environment.
set -o allexport
# shellcheck source-path=SCRIPTDIR
# shellcheck source=policy.env
source "${policy_dir}/policy.env"
set +o allexport

export CURL_HOME="${RUNNER_TEMP:-${TMPDIR:-/tmp}}/torch_tpu_network_policy"
mkdir -p "$CURL_HOME"
cat > "${CURL_HOME}/.curlrc" <<EOF
# Generated by ci/tools/network_policy/activate.sh from policy.env.
retry = ${DOWNLOAD_RETRIES}
retry-max-time = ${DOWNLOAD_RETRY_MAX_TIME}
retry-all-errors
connect-timeout = ${DOWNLOAD_CONNECT_TIMEOUT}
EOF

if [[ -n "${GITHUB_ENV:-}" ]]; then
  {
    sed -e 's/[[:space:]]*#.*//' -e '/^$/d' "${policy_dir}/policy.env"
    echo "CURL_HOME=${CURL_HOME}"
  } >> "$GITHUB_ENV"
fi
if [[ "${GITHUB_ACTIONS:-}" == "true" ]]; then
  echo "network-policy: activated (.curlrc in ${CURL_HOME})"
fi
